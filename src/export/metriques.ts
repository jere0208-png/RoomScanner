/** La largeur (pt) d'une chaîne DÉJÀ encodée en WinAnsi (un octet par signe). */
export function largeurWinAnsi(octets: string, taille: number, gras = false): number {
  const t = gras ? HELVETICA_GRAS : HELVETICA;
  let m = 0;
  for (let i = 0; i < octets.length; i++) m += t[octets.charCodeAt(i) & 0xff] ?? 556;
  return (m * taille) / 1000;
}
